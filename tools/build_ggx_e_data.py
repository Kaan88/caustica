# Generate GGX_E_DATA: the Kulla-Conty complement albedo S(mu, alpha) = 1 - E(mu, alpha)
# for the shader's own GGX form (D = a^2/(pi*(nh^2*(a^2-1)+1)^2), G1 = 2n/(n+sqrt(a^2+(1-a^2)n^2)),
# f = D*G1(nv)*G1(nl)/(4*no*nv)) on a 32x32 grid, mu = cos view angle, alpha in [0.02, 1].
# E is the hemispherical directional reflectance of a white furnace (F0=1):
#   E(mu,a) = integral f * (n.l) domega_l
# importance-sampling h from D (the same stretched-hemisphere sampler the shader uses: u on the disk,
# h = normalize((a*r*cos phi, a*r*sin phi, 1)) with r^2 = u/(1-u)) makes the estimator
#   g1(nv)*g1(nl)*(v.h)/(mu*(n.h))
# bounded, so a deterministic lattice (radical inverse base 2 and 3) converges to ~1e-5 absolute
# even at alpha = 0.02, where the plain angular grid cannot resolve the a^2-wide spike near h = n.
# Cross-checked against a direct angular quadrature at mid-range points.
import numpy as np
import numpy as np

PI = np.pi
N = 1_000_000

def radical_inv(n, base):
    out = np.zeros(n, dtype=np.float64)
    inv = 1.0 / base
    f = inv
    i = np.arange(1, n + 1, dtype=np.int64)
    while np.any(i):
        out += f * (i % base)
        i //= base
        f /= base
    return out

U = radical_inv(N, 2)
PHI = radical_inv(N, 3) * 2 * PI
R2 = U / (1.0 - U)
R = np.sqrt(R2)

def g1(n, a):
    return 2 * n / (n + np.sqrt(a * a + (1 - a * a) * n * n))

def E(mu, a):
    hx = a * R * np.cos(PHI)
    hy = a * R * np.sin(PHI)
    hn = np.sqrt(hx * hx + hy * hy + 1.0)
    hx, hy, hz = hx / hn, hy / hn, 1.0 / hn
    nh = hz
    vx = np.sqrt(max(0.0, 1 - mu * mu))
    vh = vx * hx + mu * hz
    nl = 2 * vh * hz - mu
    inside = (vh > 0) & (nl > 0)
    g1l = np.where(inside, g1(np.maximum(nl, 1e-12), a), 0.0)
    est = np.where(inside, g1(mu, a) * g1l * vh / (mu * hz), 0.0)
    return est.mean()

GRID = 32
mus = np.linspace(0.02, 1.0, GRID)
als = np.linspace(0.02, 1.0, GRID)
tab = np.array([[1.0 - E(m, a) for m in mus] for a in als])  # S = 1 - E, row-major [alpha][mu]
tab = np.clip(tab, 0.0, 1.0)

for mu0, a0 in [(0.3, 0.4), (0.5, 0.6), (0.7, 0.3)]:
    # direct angular quadrature (valid where the spike is wide enough)
    th = np.linspace(0.0004, PI / 2 - 0.0004, 2048)
    ph = np.linspace(0, 2 * PI, 1024, endpoint=False)
    thg, pg = np.meshgrid(th, ph, indexing='ij')
    nl, sl = np.cos(thg), np.sin(thg)
    vx = np.sqrt(max(0.0, 1 - mu0 * mu0))
    hx = vx + sl * np.cos(pg)
    hy = sl * np.sin(pg)
    hz = mu0 + nl
    hnn = np.sqrt(hx * hx + hy * hy + hz * hz)
    nh = hz / hnn
    a2 = a0 * a0
    D = a2 / (PI * (nh * nh * (a2 - 1) + 1) ** 2)
    f = D * g1(mu0, a0) * g1(nl, a0) / (4 * mu0 * nl)
    iphi = (f * nl * sl).sum(axis=1) * (2 * PI / 1024)
    q = np.trapezoid(iphi, th)
    m = E(mu0, a0)
    print(f"check mu={mu0} a={a0}: quad {q:.6f} lattice {m:.6f} rel {abs(q - m) / q:.2e}")

lines = [
    "// Generated by tools/build_ggx_e_data.py - do not edit by hand.",
    "/// Kulla-Conty energy-compensation table. `GGX_E_S[i * GRID + j]` is S(mu, alpha) =",
    "/// 1 - E(mu, alpha): the fraction of a white furnace (F0 = 1) that the shader's GGX lobe",
    "/// D * G1(nv) * G1(nl) / (4 no nv) FAILS to reflect at view cosine mu and roughness alpha.",
    "/// Rows are alpha, columns mu, both in [0.02,1] on 32 steps; row-major. Generated by",
    "/// integrating exactly that form with a radical-inverse lattice over the shader's own",
    "/// half-vector sampler (see the header), then stored as S because E -> 1 at small alpha",
    "/// and 1 - E would lose every digit if E were stored. Gpu::new uploads the bytes once;",
    "/// the trace binds them as StructuredBuffer<float> ggx_table (t8) and reads S bilinearly.",
    "/// The multiple-scattering term is S(nv) * S(nl) / (pi - E_avg(a)) * F_ms(f0) with",
    "/// F_ms = 0.04 f0 + 0.66 f0^2 + 0.3 f0^3 (Kulla and Conty, JCGT 8(3), and the published",
    "/// E_avg polynomial fit below).",
    "pub const GGX_E_GRID: usize = 32;",
    "pub const GGX_E_S: [f32; GGX_E_GRID * GGX_E_GRID] = [",
]
vals = tab.ravel()
row = []
for v in vals:
    row.append(f"{float(v):.7g}f32")
    if len(row) == 8:
        lines.append("    " + ", ".join(row) + ",")
        row = []
lines.append("];")
open("src/ggx_e_data.rs", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

print("S min/max:", vals.min(), vals.max())
print("S(a=0.02 row):", np.round(tab[0, ::8], 4))
print("S(a=1 row):", np.round(tab[-1, ::8], 4))
print("wrote src/ggx_e_data.rs", len(vals), "floats")
